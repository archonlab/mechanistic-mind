def is_acanthostega_public_preset(raw: Any) -> bool:
    """True when a normalized public preset belongs to the Acanthostega model line."""
    n = normalize_preset_name(raw)
    if not n:
        return False
    if n in ACANTHOSTEGA_PUBLIC_PRESET_IDS:
        return True
    # Forward-compatible: any future ACANTHOSTEGA_* id not yet listed still maps correctly.
    return n.startswith("ACANTHOSTEGA_") or n == "ACANTHOSTEGA"


