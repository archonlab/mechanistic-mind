def visibility_class_for_preset(raw: Any) -> str:
    """PUBLIC_MODEL | DEVELOPMENT_FIXTURE for registered presets."""
    n = normalize_preset_name(raw)
    if n in PUBLIC_MODEL_PRESET_IDS:
        return "PUBLIC_MODEL"
    if n is None:
        return "DEVELOPMENT_FIXTURE"
    canon = preset_canonical(n) if n else None
    if isinstance(canon, dict) and canon.get("visibility_class"):
        return str(canon["visibility_class"])
    return "DEVELOPMENT_FIXTURE"


def is_public_model_selector_entry(raw: Any) -> bool:
    """True only for Tiktaalik Beta 3.1 and Acanthostega Beta 4.0."""
    n = normalize_preset_name(raw)
    return n in PUBLIC_MODEL_PRESET_IDS


